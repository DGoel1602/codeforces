vector<int> solve(int n, int q, vector<int> &a, vector<pair<int, int>> &qu) {
    vector<int> res(q);

    vector<pair<vector<int>, int>> events(n);
    for(int i = 0; i<n; i++) {
        int end = (i + a[i]) % n, start = (i+n-a[i])%n;
        events[start].first.push_back(end);
        events[end].second++;
        if(start > end) events[0].first.push_back(end);
    }

    multiset<pair<int, int>> ms;
    vector<pair<int, int>> to(n);
    for(int i = 0; i<n; i++) {
        for(int x: events[i].first) ms.insert({x < i, x});
        to[i] = *prev(ms.end());
        for(int j = 0; j<events[i].second; j++) {
            if(ms.find({0, i}) != ms.end()) ms.erase(ms.find({0, i}));
        }
    }

    vector<vector<pair<int, int>>> lift(20, vector<pair<int, int>>(n));
    lift[0] = vector<pair<int, int>>(to);
    for(int i = 1; i<20; i++) {
        for(int j = 0; j<n; j++) {
            pair<int, int> f = lift[i-1][j];
            pair<int, int> s = lift[i-1][f.second];
            lift[i][j] = {f.first + s.first, s.second};
        }
    }

    // for(int i = 0; i<26; i++) {
    //     for(int j = 0; j<n; j++) cout << lift[i][j].first << " " << lift[i][j].second << "  ";
    //     cout << endl;
    // }

    for(int i = 0; i<q; i++) {
        int ls = 0;
        auto [u, v] = qu[i];

        // cout << u << " " << v << endl;
        if(min(abs(u - v), n - abs(u-v)) <= a[u] + a[v]) {
            res[i] = 1;
            continue;
        }

        v = (v + n - a[v]) % n;
        pair<int, int> cur = {(u+a[u])%n < u, (u+a[u])%n};
        pair<int, int> need = {v < u, v};
        for(int k = 19; k>=0; k--) {
            pair<int, int> aft = lift[k][cur.second];
            aft = {aft.first + cur.first, aft.second};
            // cout << k << " " << cur.first << " " << cur.second << " " << aft.first << " " << aft.second << endl;
            if(aft < need) ls |= (1 << k), cur = aft;
        }
        // cout << i << " " << ls << endl;
        res[i] = ls + 2;
    }

    return res;
}

